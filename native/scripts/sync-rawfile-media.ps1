# Copy bundled default media into the HAP rawfile tree and generate the ArkTS manifest.
#
# - Source: <repo>/default/content/**  (only the binary entries declared by index.json:
#   background / character / sprites / avatar)
# - Dest:   <repo>/entry/src/main/resources/rawfile/default/content/**
# - Manifest: <repo>/entry/src/main/ets/backend/MediaManifest.ets
#
# Pure ASCII on purpose: non-ASCII text in .ps1 gets decoded as the console code page and
# swallows newlines (see the porting plan, section 10.5).
param(
    [string]$RepoRoot = (Split-Path -Parent (Split-Path -Parent $PSScriptRoot))
)

$ErrorActionPreference = 'Stop'

$contentDir = Join-Path $RepoRoot 'default\content'
$rawfileDir = Join-Path $RepoRoot 'entry\src\main\resources\rawfile\default\content'
$manifestPath = Join-Path $RepoRoot 'entry\src\main\ets\backend\MediaManifest.ets'

if (-not (Test-Path $contentDir)) { throw "missing content dir: $contentDir" }

$index = Get-Content (Join-Path $contentDir 'index.json') -Raw | ConvertFrom-Json
$mediaTypes = @('background', 'character', 'sprites', 'avatar')

$entries = New-Object System.Collections.Generic.List[string]

foreach ($item in $index) {
    if ($mediaTypes -notcontains $item.type) { continue }

    $source = Join-Path $contentDir $item.filename
    if (-not (Test-Path $source)) { throw "declared content missing on disk: $($item.filename)" }

    $files = @()
    if ((Get-Item $source).PSIsContainer) {
        $files = Get-ChildItem $source -Recurse -File
    } else {
        $files = @(Get-Item $source)
    }

    foreach ($file in $files) {
        $relative = $file.FullName.Substring($contentDir.Length + 1).Replace('\', '/')
        $entries.Add($relative)

        $dest = Join-Path $rawfileDir $relative.Replace('/', '\')
        $destDir = Split-Path -Parent $dest
        if (-not (Test-Path $destDir)) { New-Item -ItemType Directory -Path $destDir -Force | Out-Null }
        Copy-Item $file.FullName $dest -Force
    }
}

$entries = $entries | Sort-Object -Unique
$totalBytes = 0
foreach ($entry in $entries) {
    $totalBytes += (Get-Item (Join-Path $contentDir $entry.Replace('/', '\'))).Length
}

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('// GENERATED by native/scripts/sync-rawfile-media.ps1 - do not edit by hand.')
[void]$sb.AppendLine('//')
[void]$sb.AppendLine('// Media entries of default/content/index.json that ship as HAP rawfile instead of being')
[void]$sb.AppendLine('// compiled into libttavern.so: embedding them would cost one copy per ABI (2x 7.4 MB),')
[void]$sb.AppendLine('// while rawfile is stored once (see the porting plan, section 11.2-B).')
[void]$sb.AppendLine('//')
[void]$sb.AppendLine('// Paths are relative to default/ and mirror the backend media root layout')
[void]$sb.AppendLine('// (<filesDir>/.bundled-media/<entry>). Regenerate after changing default/content.')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('/** Number of media files packed into the HAP rawfile tree. */')
[void]$sb.AppendLine("export const MEDIA_FILE_COUNT: number = $($entries.Count);")
[void]$sb.AppendLine('')
[void]$sb.AppendLine('/** Total size of those files, for diagnostics only. */')
[void]$sb.AppendLine("export const MEDIA_TOTAL_BYTES: number = $totalBytes;")
[void]$sb.AppendLine('')
[void]$sb.AppendLine('/** rawfile path -> media-root relative path (both identical: content/<...>). */')
[void]$sb.AppendLine('export const MEDIA_MANIFEST: string[] = [')
foreach ($entry in $entries) {
    [void]$sb.AppendLine("  'content/$entry',")
}
[void]$sb.AppendLine('];')
[void]$sb.AppendLine('')

[System.IO.File]::WriteAllText($manifestPath, $sb.ToString(), (New-Object System.Text.UTF8Encoding($false)))

Write-Host ("media files copied : {0}" -f $entries.Count)
Write-Host ("media total bytes  : {0:N0}" -f $totalBytes)
Write-Host ("rawfile dir        : {0}" -f $rawfileDir)
Write-Host ("manifest           : {0}" -f $manifestPath)
