//! Bundled default content store (replaces Tauri's resource-bundle reads).
//!
//! Upstream reads `default/**` from the Tauri resource directory through
//! `infrastructure::assets::{read_resource_json, read_resource_text, copy_resource_to_file,
//! list_default_files_under}`. On OHOS no such directory exists for native code, so the two
//! asset classes take different routes:
//!
//! - **Text** (138 files, ~200 KB): compiled into the `.so` by `build.rs`
//!   (`EMBEDDED_TEXT_RESOURCES`).
//! - **Media** (56 PNG/JPG files, ~7.6 MB): shipped as HAP `rawfile` and extracted once by
//!   ArkTS into `<filesDir>/.bundled-media/` (see `BundledMedia.ets`), because embedding them
//!   would cost 7.6 MB *per ABI* instead of 7.6 MB once.
//!
//! Both spellings `default/content/x.json` and bare `content/x.json` are accepted; the media
//! root is keyed by the normalized path (no `default/` prefix).

use std::path::{Path, PathBuf};

use tt_domain::errors::DomainError;
use tt_ports::bundled_template::BundledTemplateStore;

// Generated by build.rs: `pub static EMBEDDED_TEXT_RESOURCES: &[(&str, &str)]`.
include!(concat!(env!("OUT_DIR"), "/embedded_resources.rs"));

const UPSTREAM_PREFIX: &str = "default/";

/// Read-only view over the bundled `default/` assets: compiled-in text plus an optional
/// on-disk media root extracted from HAP `rawfile`.
#[derive(Debug, Clone, Default)]
pub struct BundledResourceStore {
    media_root: Option<PathBuf>,
}

impl BundledResourceStore {
    /// Attach the directory ArkTS extracted the `rawfile` media into.
    pub fn with_media_root(media_root: Option<PathBuf>) -> Self {
        Self { media_root }
    }

    pub fn media_root(&self) -> Option<&Path> {
        self.media_root.as_deref()
    }

    /// Number of embedded text assets (surfaced in `get_backend_status` diagnostics).
    pub fn len(&self) -> usize {
        EMBEDDED_TEXT_RESOURCES.len()
    }

    /// Number of files available from the extracted media root (0 when not attached).
    pub fn media_len(&self) -> usize {
        self.list_media_under("").len()
    }

    /// Resolve a bundle-relative path to its embedded text content.
    pub fn read_text(&self, relative_path: &str) -> Result<&'static str, DomainError> {
        let key = normalize(relative_path);
        EMBEDDED_TEXT_RESOURCES
            .iter()
            .find(|(path, _)| *path == key)
            .map(|(_, body)| *body)
            .ok_or_else(|| {
                DomainError::NotFound(format!("bundled resource not found: {relative_path}"))
            })
    }

    /// Resolve a bundle-relative path to raw bytes: embedded text first, then media root.
    pub fn read_bytes(&self, relative_path: &str) -> Result<Vec<u8>, DomainError> {
        let key = normalize(relative_path);

        if let Some((_, body)) = EMBEDDED_TEXT_RESOURCES.iter().find(|(path, _)| *path == key) {
            return Ok(body.as_bytes().to_vec());
        }

        if let Some(root) = &self.media_root {
            let candidate = root.join(&key);
            if candidate.is_file() {
                return std::fs::read(&candidate).map_err(|error| {
                    DomainError::file_io(
                        "read bundled media",
                        candidate.display().to_string(),
                        error,
                    )
                });
            }
        }

        Err(DomainError::NotFound(format!(
            "bundled resource not found: {relative_path}"
        )))
    }

    /// All bundle entries under `prefix` (e.g. `content/presets/context`), sorted.
    ///
    /// Embedded text entries are always listed; media entries appear only when the media root
    /// is attached, which is how `sprites/Seraphina` resolves to its 28 PNG files.
    pub fn list_under(&self, prefix: &str) -> Vec<String> {
        let key = normalize(prefix);
        let key = key.trim_end_matches('/').to_string();

        let mut entries: Vec<String> = EMBEDDED_TEXT_RESOURCES
            .iter()
            .filter(|(path, _)| is_under(path, &key))
            .map(|(path, _)| (*path).to_string())
            .collect();

        if self.media_root.is_some() {
            entries.extend(self.list_media_under(&key));
        }

        entries.sort();
        entries.dedup();
        entries
    }

    /// Copy one bundled asset (text or media) to `dest`, creating parent directories.
    pub fn copy_to(&self, relative_path: &str, dest: &Path) -> Result<(), DomainError> {
        let bytes = self.read_bytes(relative_path)?;
        if let Some(parent) = dest.parent() {
            std::fs::create_dir_all(parent).map_err(|error| {
                DomainError::file_io(
                    "create bundled asset parent",
                    parent.display().to_string(),
                    error,
                )
            })?;
        }
        std::fs::write(dest, bytes).map_err(|error| {
            DomainError::file_io("write bundled asset", dest.display().to_string(), error)
        })
    }

    /// Walk the media root and return keys relative to it.
    fn list_media_under(&self, key: &str) -> Vec<String> {
        let Some(root) = &self.media_root else {
            return Vec::new();
        };

        let start = if key.is_empty() {
            root.clone()
        } else {
            root.join(key)
        };

        let mut out = Vec::new();
        collect_files(root, &start, key, &mut out);
        out
    }
}

impl BundledTemplateStore for BundledResourceStore {
    fn read_text(&self, relative_path: &str) -> Result<String, DomainError> {
        BundledResourceStore::read_text(self, relative_path).map(str::to_string)
    }
}

fn is_under(path: &str, key: &str) -> bool {
    key.is_empty() || path == key || path.starts_with(&format!("{key}/"))
}

/// Recursively collect regular files under `dir`, producing keys relative to `root`.
fn collect_files(root: &Path, dir: &Path, key: &str, out: &mut Vec<String>) {
    let Ok(read_dir) = std::fs::read_dir(dir) else {
        return;
    };

    for entry in read_dir.flatten() {
        let path = entry.path();
        let Ok(file_type) = entry.file_type() else {
            continue;
        };
        if file_type.is_dir() {
            collect_files(root, &path, key, out);
            continue;
        }
        if !file_type.is_file() {
            continue;
        }
        let Ok(relative) = path.strip_prefix(root) else {
            continue;
        };
        let normalized = relative
            .components()
            .map(|component| component.as_os_str().to_string_lossy().to_string())
            .collect::<Vec<_>>()
            .join("/");
        if is_under(&normalized, key) {
            out.push(normalized);
        }
    }
}

/// `"default/content/index.json"`, `"content/index.json"`, `"./content/index.json"` → `"content/index.json"`.
fn normalize(relative_path: &str) -> String {
    let path = relative_path.trim().replace('\\', "/");
    let path = path.trim_start_matches("./");
    let path = path.strip_prefix(UPSTREAM_PREFIX).unwrap_or(path);
    path.trim_start_matches('/').to_string()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn normalizes_upstream_spellings() {
        assert_eq!(normalize("default/content/index.json"), "content/index.json");
        assert_eq!(normalize("content/index.json"), "content/index.json");
        assert_eq!(normalize("./content\\index.json"), "content/index.json");
        assert_eq!(normalize("/content/index.json"), "content/index.json");
    }

    #[test]
    fn reads_settings_and_lists_presets() {
        let store = BundledResourceStore::default();
        let settings = store
            .read_text("default/content/settings.json")
            .expect("settings.json must be embedded");
        assert!(settings.trim_start().starts_with('{'));
        assert!(!store.list_under("content/presets/context").is_empty());
    }

    #[test]
    fn missing_resource_is_not_found_error() {
        let store = BundledResourceStore::default();
        assert!(matches!(
            store.read_text("content/does-not-exist.json"),
            Err(DomainError::NotFound(_))
        ));
        assert!(matches!(
            store.read_bytes("content/does-not-exist.json"),
            Err(DomainError::NotFound(_))
        ));
    }
}
