//! Build script for the NAPI host crate.
//!
//! Two jobs:
//! 1. `napi_build_ohos::setup()` — OHOS NAPI link settings.
//! 2. Generate `OUT_DIR/embedded_resources.rs`: a `&[(relative_path, &'static str)]`
//!    table of the SillyTavern-compatible default content that ships inside the `.so`.
//!
//! Why embed instead of reading Tauri's resource bundle:
//! the upstream host reads `default/**` through `AppHandle` (Tauri resource dir). OHOS has
//! no such directory visible to native code, so text assets are compiled in via `include_str!`.
//! Binary/media assets (backgrounds, sprites, avatars — ~7.3 MB) are deliberately NOT embedded:
//! they are delivered as HAP rawfiles and materialized in P4.

use std::path::{Path, PathBuf};

/// Text extensions worth embedding (JSON templates, presets, themes, builtin skill docs…).
const TEXT_EXTENSIONS: &[&str] = &["json", "yaml", "yml", "txt", "md", "css", "html", "tpl"];
/// Subtrees skipped for now. `skills/` (~296 KB of builtin skill docs) is only consumed by
/// `materialize_builtin_skills`, which belongs to the skills phase (P6).
const SKIP_DIRS: &[&str] = &["skills"];

fn main() {
    napi_build_ohos::setup();
    generate_embedded_resources();
}

fn generate_embedded_resources() {
    // native/crates/ttavern -> native/crates -> native -> <repo root>
    let manifest_dir = PathBuf::from(
        std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR is set by cargo"),
    );
    let repo_root = manifest_dir
        .parent()
        .and_then(Path::parent)
        .and_then(Path::parent)
        .expect("host crate must live at native/crates/ttavern")
        .to_path_buf();
    let default_dir = repo_root.join("default");

    let out_dir = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR is set by cargo"));
    let out_file = out_dir.join("embedded_resources.rs");

    println!("cargo:rerun-if-changed={}", default_dir.display());
    println!("cargo:rerun-if-changed=build.rs");

    let mut entries: Vec<(String, PathBuf)> = Vec::new();
    if default_dir.is_dir() {
        collect(&default_dir, &default_dir, &mut entries);
    }
    // Deterministic order keeps the generated file stable across builds.
    entries.sort_by(|a, b| a.0.cmp(&b.0));

    let mut out = String::new();
    out.push_str("// @generated by crates/ttavern/build.rs — do not edit.\n");
    out.push_str(&format!(
        "// {} text assets embedded from <repo>/default (skills/ excluded: P6).\n",
        entries.len()
    ));
    out.push_str("pub static EMBEDDED_TEXT_RESOURCES: &[(&str, &str)] = &[\n");
    for (rel, abs) in &entries {
        let literal_path = abs.to_string_lossy().replace('\\', "/");
        out.push_str(&format!(
            "    ({:?}, include_str!(r\"{}\")),\n",
            rel, literal_path
        ));
    }
    out.push_str("];\n");

    std::fs::write(&out_file, out).expect("failed to write embedded_resources.rs");
}

fn collect(root: &Path, dir: &Path, out: &mut Vec<(String, PathBuf)>) {
    let Ok(read_dir) = std::fs::read_dir(dir) else {
        return;
    };
    for entry in read_dir.flatten() {
        let path = entry.path();
        let Ok(file_type) = entry.file_type() else {
            continue;
        };
        if file_type.is_dir() {
            if let Some(name) = path.file_name().and_then(|n| n.to_str()) {
                if SKIP_DIRS.contains(&name) {
                    continue;
                }
            }
            collect(root, &path, out);
            continue;
        }
        let is_text = path
            .extension()
            .and_then(|e| e.to_str())
            .map(|e| TEXT_EXTENSIONS.contains(&e.to_ascii_lowercase().as_str()))
            .unwrap_or(false);
        if !is_text {
            continue;
        }
        let Ok(rel) = path.strip_prefix(root) else {
            continue;
        };
        let rel = rel.to_string_lossy().replace('\\', "/");
        out.push((rel, path));
    }
}
